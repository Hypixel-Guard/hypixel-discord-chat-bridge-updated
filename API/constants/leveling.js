/**
 * Converts a list of per-level xp increments into a { 1: xp, 2: xp, ... } table.
 * @param {number[]} increments
 * @returns {Record<number, number>}
 */
function toXpTable(increments) {
  return Object.fromEntries(increments.map((xp, index) => [index + 1, xp]));
}

